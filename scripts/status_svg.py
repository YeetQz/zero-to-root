"""🖼️ Draws assets/status.svg: an animated Solo Leveling style status window.

GitHub shows SVG images with their CSS animations, so this plays right in the README:
the window glows, lines fade in one by one, the XP and stat bars fill up,
and the rank letter pulses. Regenerated by the README bot on every push.
"""
from __future__ import annotations

from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "status.svg"

RANK_COLORS = {"E": "#9aa4b8", "D": "#3fd68f", "C": "#3ad9ff", "B": "#4c8dff", "A": "#b48cff", "S": "#ffcf40"}
RANK_ORDER = ["E", "D", "C", "B", "A", "S"]


def render(h) -> str:
    W, H = 860, 470
    rank_col = RANK_COLORS.get(h.rank, "#3ad9ff")
    xp_w = 420 * (h.xp_into_level / h.xp_per_level if h.xp_per_level else 0)
    stats = list(h.stats.items())
    max_stat = max([v for v, _ in h.stats.values()] + [40])

    parts: list[str] = []
    add = parts.append
    add(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" role="img" '
        f'aria-label="Hunter status: {escape(h.name)}, level {h.level}, {h.rank}-rank, {h.xp} XP">')
    add("""<defs>
  <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#050b1a"/><stop offset="1" stop-color="#0b1a3a"/>
  </linearGradient>
  <linearGradient id="xp" x1="0" x2="1">
    <stop offset="0" stop-color="#1f6bff"/><stop offset="1" stop-color="#3ad9ff"/>
  </linearGradient>
  <filter id="glow" x="-20%" y="-20%" width="140%" height="140%">
    <feGaussianBlur stdDeviation="4" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
  </filter>
  <pattern id="grid" width="24" height="24" patternUnits="userSpaceOnUse">
    <path d="M24 0H0V24" fill="none" stroke="#1d3a6e" stroke-width="0.5" opacity="0.35"/>
  </pattern>
</defs>
<style>
  text { font-family: 'Segoe UI', 'Helvetica Neue', Arial, sans-serif; fill: #d9e6ff; }
  .mono { font-family: 'Cascadia Mono', Consolas, 'DejaVu Sans Mono', monospace; }
  .dim { fill: #7f93bd; }
  .label { font-size: 13px; letter-spacing: 2px; fill: #7f93bd; }
  .frame { animation: pulse 3.2s ease-in-out infinite; }
  @keyframes pulse { 0%,100% { stroke-opacity: .55 } 50% { stroke-opacity: 1 } }
  .line { opacity: 0; animation: in .5s ease-out forwards; }
  @keyframes in { from { opacity: 0; transform: translateX(-8px) } to { opacity: 1; transform: none } }
  .fill { transform-box: fill-box; transform-origin: left; transform: scaleX(0); animation: grow 1.4s cubic-bezier(.2,.8,.2,1) forwards; }
  @keyframes grow { to { transform: scaleX(1) } }
  .rank { transform-box: fill-box; transform-origin: center; animation: beat 2.4s ease-in-out infinite 1.6s; }
  @keyframes beat { 0%,100% { transform: scale(1) } 50% { transform: scale(1.06) } }
  .spark { animation: rise linear infinite; opacity: 0; }
  @keyframes rise { 0% { opacity: 0; transform: translateY(0) } 15% { opacity: .9 } 100% { opacity: 0; transform: translateY(-140px) } }
  .scan { animation: sweep 5s linear infinite; }
  @keyframes sweep { from { transform: translateY(-40px) } to { transform: translateY(500px) } }
  @media (prefers-reduced-motion: reduce) { * { animation: none !important; opacity: 1 !important; transform: none !important; } }
</style>""")

    # background, grid, scanning light
    add(f'<rect width="{W}" height="{H}" rx="14" fill="url(#bg)"/>')
    add(f'<rect width="{W}" height="{H}" rx="14" fill="url(#grid)"/>')
    add(f'<rect class="scan" x="0" y="0" width="{W}" height="40" fill="#3ad9ff" opacity="0.05"/>')

    # rising sparks
    for i, (x, dur, delay) in enumerate([(70, 6, 0), (180, 7.5, 2), (330, 6.5, 4), (520, 8, 1), (640, 7, 3), (790, 6, 5)]):
        add(f'<circle class="spark" cx="{x}" cy="{H - 20}" r="{1.6 + (i % 3) * 0.6}" fill="#3ad9ff" '
            f'style="animation-duration:{dur}s;animation-delay:{delay}s"/>')

    # glowing frame with corner brackets
    add(f'<rect class="frame" x="16" y="16" width="{W - 32}" height="{H - 32}" rx="10" fill="none" '
        f'stroke="#3ad9ff" stroke-width="1.5" filter="url(#glow)"/>')
    for x, y, dx, dy in [(16, 16, 1, 1), (W - 16, 16, -1, 1), (16, H - 16, 1, -1), (W - 16, H - 16, -1, -1)]:
        add(f'<path d="M{x} {y + 26 * dy}V{y}H{x + 26 * dx}" fill="none" stroke="#9feaff" stroke-width="3"/>')

    # title
    add(f'<g class="line" style="animation-delay:.1s"><text x="{W / 2}" y="58" text-anchor="middle" '
        f'font-size="24" font-weight="700" letter-spacing="10" fill="#9feaff" filter="url(#glow)">STATUS</text>'
        f'<line x1="250" y1="72" x2="{W - 250}" y2="72" stroke="#3ad9ff" stroke-opacity=".5"/></g>')

    # identity block
    y0 = 112
    rows = [
        ("NAME", escape(h.name)), ("JOB", escape(h.job)), ("TITLE", escape(h.title)),
    ]
    for i, (k, v) in enumerate(rows):
        add(f'<g class="line" style="animation-delay:{.3 + i * .15:.2f}s">'
            f'<text class="label" x="48" y="{y0 + i * 34}">{k}</text>'
            f'<text x="130" y="{y0 + i * 34}" font-size="20" font-weight="600">{v}</text></g>')

    # level + rank emblem (right)
    add(f'<g class="line" style="animation-delay:.45s">'
        f'<text class="label" x="560" y="{y0}">LEVEL</text>'
        f'<text x="560" y="{y0 + 58}" font-size="62" font-weight="800" fill="#ffffff" filter="url(#glow)">{h.level}</text></g>')
    cx, cy = 742, y0 + 22
    add(f'<g class="line" style="animation-delay:.6s"><g class="rank">'
        f'<circle cx="{cx}" cy="{cy}" r="46" fill="none" stroke="{rank_col}" stroke-width="2.5" filter="url(#glow)"/>'
        f'<circle cx="{cx}" cy="{cy}" r="38" fill="{rank_col}" fill-opacity=".1"/>'
        f'<text x="{cx}" y="{cy + 17}" text-anchor="middle" font-size="48" font-weight="800" fill="{rank_col}" '
        f'filter="url(#glow)">{h.rank}</text></g>'
        f'<text class="label" x="{cx}" y="{cy + 70}" text-anchor="middle">RANK</text></g>')

    # XP bar
    yb = 236
    add(f'<g class="line" style="animation-delay:.9s">'
        f'<text class="label" x="48" y="{yb + 14}">XP</text>'
        f'<rect x="130" y="{yb}" width="420" height="16" rx="8" fill="#13274d"/>'
        f'<rect class="fill" x="130" y="{yb}" width="{max(xp_w, 0.1):.1f}" height="16" rx="8" fill="url(#xp)" '
        f'filter="url(#glow)" style="animation-delay:1.1s"/>'
        f'<text class="mono" x="566" y="{yb + 14}" font-size="14">{h.xp_into_level} / {h.xp_per_level}</text>'
        f'<text class="dim" x="130" y="{yb + 38}" font-size="13">{h.xp} XP total · '
        f'{h.xp_per_level - h.xp_into_level} XP to level {h.level + 1}</text></g>')

    # stats (two columns)
    add(f'<line x1="48" y1="296" x2="{W - 48}" y2="296" stroke="#3ad9ff" stroke-opacity=".25"/>')
    for i, (key, (val, name)) in enumerate(stats):
        col, r = i % 2, i // 2
        x = 48 + col * 400
        y = 330 + r * 34
        bw = 170 * val / max_stat
        add(f'<g class="line" style="animation-delay:{1.2 + i * .12:.2f}s">'
            f'<text x="{x}" y="{y}" font-size="16" font-weight="700" fill="#9feaff">{key}</text>'
            f'<text class="dim" x="{x + 48}" y="{y}" font-size="14">{escape(name)}</text>'
            f'<rect x="{x + 160}" y="{y - 11}" width="170" height="8" rx="4" fill="#13274d"/>'
            f'<rect class="fill" x="{x + 160}" y="{y - 11}" width="{bw:.1f}" height="8" rx="4" fill="#3fd68f" '
            f'style="animation-delay:{1.4 + i * .12:.2f}s"/>'
            f'<text class="mono" x="{x + 342}" y="{y}" font-size="15">{val}</text></g>')

    # rank ladder
    ly = H - 42
    add(f'<g class="line" style="animation-delay:2s">')
    add(f'<text class="label" x="448" y="{ly + 5}">RANK LADDER</text>')
    for i, r in enumerate(RANK_ORDER):
        x = 590 + i * 38
        on = RANK_ORDER.index(h.rank) >= i if h.rank in RANK_ORDER else False
        cur = r == h.rank
        colr = RANK_COLORS[r]
        glow = ' filter="url(#glow)"' if cur else ""
        add(f'<rect x="{x - 14}" y="{ly - 14}" width="28" height="28" rx="6" fill="{colr if on else "none"}" '
            f'fill-opacity="{.22 if on else 0}" stroke="{colr}" stroke-opacity="{1 if on else .35}" '
            f'stroke-width="{2.5 if cur else 1.2}"{glow}/>')
        add(f'<text x="{x}" y="{ly + 6}" text-anchor="middle" font-size="15" font-weight="700" '
            f'fill="{colr}" fill-opacity="{1 if on else .45}">{r}</text>')
    add('</g>')

    add("</svg>")
    return "\n".join(parts)


def write(h) -> Path:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(h), encoding="utf-8")
    return OUT
